"""Write standalone ngspice decks for build A to sim/spice/ from the same generator the analyses use.
Run from sim/scripts. The decks include ./models_bjt.lib relative to sim/spice/."""
import gen, os, shutil, numpy as np
A10 = np.sqrt(2 * 50 * 10 ** (-10 / 10) / 1000) * 2      # EMF for -10 dBm available per tone, as in gen.twotone
STEP = 1 / (80 * (2 * 7.2e6 + 7e6)); TT = 10 / 0.2e6
P = gen.params("A")
out = os.path.join(gen.HERE, "..", "spice"); os.makedirs(out, exist_ok=True)
shutil.copy(gen.MODELS, os.path.join(out, "models_bjt.lib"))
nodes = " ".join(f"v(p{k})" for k in range(1, P['NPORT'] + 1))
decks = {
 "tb_op.cir": ("op\nprint v(x) v(out) v(vcc) @q1n[ic] @q1p[ic] @q2[ic] @q3[ic] i(vcc)", "RGIN IN 0 50\n" + gen.portloads(P), "", None),
 "tb_ac_forward.cir": ("ac dec 40 1e3 200e6\nwrdata ac_forward.txt v(in) " + nodes, gen.src50(P) + "\n" + gen.portloads(P), "", None),
 "tb_ac_isolation.cir": ("ac dec 40 1e3 200e6\nwrdata ac_isolation.txt v(in) " + nodes, "RGIN IN 0 50\n" + gen.portloads(P, drive=2), "", None),
 "tb_noise.cir": ("noise v(p1) vgin dec 1 10e6 10e6 1\nsetplot noise1\nprint all", gen.src50(P) + "\n" + gen.portloads(P), "", 16.85),
 "tb_twotone_7MHz.cir": (f"tran {STEP:.6g} {20e-6+TT:.6g} 20e-6 {STEP:.6g}\nlinearize v(p1)\nwrdata twotone.txt v(p1)",
     f"V1 G 0 SIN(0 {A10:.6g} 7e6)\nV2 G GG SIN(0 {A10:.6g} 7.2e6)\nRGIN GG IN 50\n" + gen.portloads(P),
     ".options reltol=1e-6 abstol=1e-14 vntol=1e-9 method=trap", None),
 "tb_full_supply_op.cir": ("op\nprint v(vcc) v(uout) v(uin) i(vin)", "RGIN IN 0 50\n" + gen.portloads(P), "", "full"),
}
for fn, (an, loads, extra, special) in decks.items():
    PP = dict(P)
    if special == "full": PP['SUPPLY'] = 'full'
    elif special: PP['TEMP'] = special
    txt = gen.netlist(PP, an, loads, extra).replace(f".include {gen.MODELS}", ".include models_bjt.lib")
    hdr = f"* Generated by sim/scripts/export_netlists.py from gen.params('A') - build A: " + \
          ", ".join(f"{k}={P[k]}" for k in gen.BUILDS['A']) + "\n* Run: cd sim/spice && ngspice -b " + fn + "\n"
    open(os.path.join(out, fn), "w").write(hdr + txt)
    print("wrote", fn)
